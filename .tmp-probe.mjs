import { chromium } from 'playwright-core';
const CHROME='C:/Users/张一/AppData/Local/ms-playwright/chromium-1248/chrome-win64/chrome.exe';
const b=await chromium.launch({executablePath:CHROME});
const p=await b.newPage({viewport:{width:1440,height:1000},deviceScaleFactor:1});
const urls=new Set();
p.on('response',(r)=>{const u=r.url(); if(/\.(jpg|jpeg|png|webp|avif)/.test(u)) urls.add(u);});
await p.goto('https://watch.chromaawards.com/',{waitUntil:'networkidle',timeout:60000}).catch(e=>console.log('nav',e.message));
await p.waitForTimeout(4000);
const text=await p.evaluate(()=>document.body.innerText.slice(0,1500));
console.log('TEXT>>>',text.replace(/\n+/g,' | ').slice(0,900));
const cards=await p.evaluate(()=>[...document.querySelectorAll('a')].slice(0,60).map(a=>a.getAttribute('href')));
console.log('LINKS>>>',JSON.stringify(cards.filter(h=>h&&h.includes('submission')).slice(0,20)));
console.log('IMG>>>',[...urls].slice(0,25).join('\n'));
await p.screenshot({path:'.tmp/chroma-gallery.png',fullPage:false});
await b.close();
